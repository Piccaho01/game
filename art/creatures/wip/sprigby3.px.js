const LINE = { u: "F", U: "F", f: "F", c: "F", C: "F", l: "G", L: "G", g: "G", G: "G", F: "F" }

function body(c, dy = 0) {
  const rows = FILL.trim().split("\n").map((r) => r.trim()), H = rows.length, W = rows[0].length
  const X0 = 48 - (W >> 1), Y0 = 92 - H
  const at = (x, y) => (x < 0 || y < 0 || x >= W || y >= H ? "." : rows[y][x])
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const k = at(x, y)
    if (k !== ".") { c.px(X0 + x, Y0 + y + dy, k); continue }
    const n = [[1, 0], [-1, 0], [0, 1], [0, -1]].find(([dx, dy2]) => at(x + dx, y + dy2) !== ".")
    if (!n) continue
    const lit = (n[0] === 1 || n[1] === 1) && at(x - 1, y) === "." && at(x, y - 1) === "."
    c.px(X0 + x, Y0 + y + dy, lit ? LINE[at(x + n[0], y + n[1])] : "k")
  }
  return [X0, Y0 + dy]
}

// Face and small details, in fill-grid coordinates (X, Y = the grid's canvas origin).
// Plant face, cocky: a brow angled down at the nose over a smug half-lidded eye (dark eye,
// white shine, green iris low); a dark nose; a smirk with a grass sprig chewed in its corner.
function details(c, [X, Y]) {
  const at = (x, y, rows) => c.grid(X + x, Y + y, rows)
  // near eye, built like Snivy's: a flat lid in the fur's dark tone pressed down over the eye
  // (smug), white showing round a green iris ring and a small pupil up front, a white shine
  at(15, 15, `
    .FFFFF
    fwgkgw
    fwkwkg
    .fwggf`)
  // far eye: the same eye turned away (narrower, same height)
  at(9, 15, `
    FFF
    gkg
    kwg
    .gf`)
  // nose: a dark dot on the snout tip
  at(2, 21, `kk`)
  // smirk: tiny, hitched up on the near side; the grass sprig poking out of its corner
  at(1, 22, `
    ......k
    ....kk.
    ..gg...
    .g.....
    Ll.....`)
  // vine tape on the fists
  at(16, 34, `GgGG`)
  at(5, 33, `GG`)
  // toes on the near foot
  at(12, 41, `F..F`)
}

sprite("sprigby3", { w: 96, h: 96 }, (c) => details(c, body(c)))
