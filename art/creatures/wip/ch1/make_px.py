# Writes art/creatures/<name>.px.js from the Chapter 1 plain conversions (this folder, white
# pockets cleared by holes.py). Same layout as wip/m7/hi/make_px.py: 192 canvas, feet on y=184,
# floaters on y=178. Idle: art/tools/idle_fx.py (art/creatures/idle_fx.json).
import sys,os
D=os.path.dirname(os.path.abspath(__file__))
INFO={
 'voltcalf':('Voltcalf, Spark Route 1 uncommon stage 1 (bible §15).',0),
 'voltaurus':('Voltaurus, Spark stage 2, evolves from Voltcalf with a Storm Shard (bible §15).',0),
 'wardeye':('Wardeye, Dark/Relic Route 1 rare quest Patchling, single stage (bible §15). Floats.',1),
}
def load(f):
    L=open(os.path.join(D,f)).read().rstrip('\n').split('\n'); return eval(L[0]),L[1:]
for name in sys.argv[1:] or INFO:
    desc,fly=INFO[name]
    P,F=load(name+'.txt'); PB,B=load(name+'_back.txt')
    inv={v:k for k,v in P.items()}; B=[''.join(inv.get(PB.get(ch,''),ch) for ch in r) for r in B]
    out=[f'// {desc} 192x192 double-res battle sprite (shown at half size in game).',
         f'// Converted from the owner\'s ChatGPT front+back pair (art/concepts/{name}_sprites.png, split to _front/_back) with',
         '// art/tools/draft2sprite.py (wip/ch1/conv.py), shared 15-colour palette. Generated by wip/ch1/make_px.py.',
         '// Idle: art/tools/idle_fx.py (per-creature effects in art/creatures/idle_fx.json).','','pal({']+[f'  {k}: "{v}",' for k,v in sorted(P.items())]+['})','']
    for tag,rows in (('FRONT',F),('BACK',B)):
        h=len(rows); w=max(len(r) for r in rows); rows=[r.ljust(w,'.') for r in rows]
        x=(192-w)//2; y=max(0,(178-h) if fly else (184-h))
        out.append(f'const {tag} = `\n'+'\n'.join('  '+r for r in rows)+'`')
        out.append(f'sprite("{name}{"" if tag=="FRONT" else "_back"}", {{ w: 192, h: 192 }}, (c) => c.grid({x}, {y}, {tag}))')
    open(os.path.join(D,'..','..',name+'.px.js'),'w').write('\n'.join(out)+'\n')
    print(name)
