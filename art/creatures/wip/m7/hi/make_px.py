# Writes art/creatures/<name>.px.js from the plain conversions (wip/m7/<name>.txt, <name>_back.txt):
# still = the converted grid, idle = 12 frames: a 1px breath (rows above 40% height drop 1px in
# frames 4-9) for walkers, a 1px hover of the whole grid for floaters and flyers. Feet on y = 91.
import sys,os
D=os.path.dirname(os.path.abspath(__file__))
INFO={
 'sprigby':('sprigby','Sprigby (sprig + wallaby), Plant starter stage 1. Redrawn M7 from the owner\'s new ChatGPT pair (the old one is wip/sprigby_v1.px.js).',0),
 'cullet':('cullet','Cullet, Fire starter stage 2 (bible §13).',0),'vitric':('vitric','Vitric, Fire/Rock starter stage 3 (bible §13).',0),
 'tesnail':('tesnail','Tesnail, Spark/Metal starter stage 2 (bible §13).',0),'gauslug':('gauslug','Gauslug, Spark/Metal starter stage 3 (bible §13).',0),
 'fernaroo':('fernaroo','Fernaroo, Plant/Wind starter stage 2 (bible §13).',0),'scytharoo':('scytharoo','Scytharoo, Plant/Wind starter stage 3 (bible §13).',0),
 'gulpjaw':('gulpjaw','Gulpjaw, Water starter stage 2 (bible §13). Throat glow removed by the owner\'s call (kept for Harrowjaw).',0),'harrowjaw':('harrowjaw','Harrowjaw, Water/Dark starter stage 3 (bible §13), converted 25% bigger in Chapter 1 (owner: it read smaller than Gulpjaw; the M7 size is harrowjaw_m7size*.txt), on a wider canvas',0),
 'orbitot':('orbitot','Orbitot, Rock/Dark Route 1 stage 1 (bible §15), redone double-res M7 from its original drafts (96 version: wip/orbitot_96.px.js). Floats.',1),
 'fledjet':('fledjet','Fledjet, Wind Route 1 stage 1 (bible §15), redone double-res M7 from its original drafts (96 version: wip/fledjet_96.px.js). Flies.',1),
 'furnaxol':('furnaxol','Furnaxol, Fire starter stage 1 (bible §13), redrawn double-res M7 from the owner\'s new pair (96 version: wip/furnaxol_96.px.js).',0),
 'zapail':('zapail','Zapail, Spark starter stage 1 (bible §13), redrawn double-res M7 (96 version: wip/zapail_96.px.js).',0),
 'gobbin':('gobbin','Gobbin, Water starter stage 1 (bible §13), redrawn double-res M7, throat glow removed (96 version: wip/gobbin_96.px.js).',0),
 'craterra':('craterra','Craterra, Rock/Dark Route 1 stage 2 (bible §15). Floats.',1),'singulith':('singulith','Singulith, Rock/Dark stage 3 (bible §15). Floats.',1),
 'contrailon':('contrailon','Contrailon, Wind/Metal stage 2 (bible §15). Flies.',1),'strafalcon':('strafalcon','Strafalcon, Wind/Metal stage 3 (bible §15). Flies.',1),
}
def load(f):
    L=open(os.path.join(D,f)).read().rstrip('\n').split('\n'); return eval(L[0]),L[1:]
for name in sys.argv[1:]:
    src,desc,fly=INFO[name]
    P,F=load(src+'.txt'); PB,B=load(src+'_back.txt')
    # The back's letters can name the shared colours in another order: map them by colour.
    inv={v:k for k,v in P.items()}; B=[''.join(inv.get(PB.get(ch,''),ch) for ch in r) for r in B]
    out=[f'// {desc} 192x192 double-res battle sprite (shown at half size in game, owner\'s call M7).',
         f'// Converted from the owner\'s ChatGPT front+back pair (art/concepts/{src}{'' if src in ('orbitot','fledjet') else '_v2_front' if src in ('furnaxol','zapail','gobbin') else '_front'}.png, _back.png) with',
         '// art/tools/draft2sprite.py at twice the 96 size (wip/m7/hi/conv2x.py), shared 15-colour palette. Generated by wip/m7/make_px.py.',
         '// Idle: art/tools/idle_fx.py (per-creature effects in art/creatures/idle_fx.json).','','pal({']+[f'  {k}: "{v}",' for k,v in sorted(P.items())]+['})','']
    def place(rows):
        # 192 square, or wider for a pose that doesn't fit (Harrowjaw's snout): still 192 tall,
        # so the game draws it at half size like the rest (BootScene monScale goes by height).
        h=len(rows); w=max(len(r) for r in rows); rows=[r.ljust(w,'.') for r in rows]
        cw=192 if w<=188 else w+8+(w%2)
        x=(cw-w)//2; y=(178-h) if fly else (184-h); return x,max(0,y),rows,cw
    for tag,rows in (('FRONT',F),('BACK',B)):
        x,y,rows,cw=place(rows)
        out.append(f'const {tag} = `\n'+'\n'.join('  '+r for r in rows)+'`')
        out.append(f'sprite("{name}{"" if tag=="FRONT" else "_back"}", {{ w: {cw}, h: 192 }}, (c) => c.grid({x}, {y}, {tag}))')
    open(os.path.join(D,'..','..','..',name+'.px.js'),'w').write('\n'.join(out)+'\n')
    print(name)
