# Writes art/creatures/<name>.px.js from the plain conversions (wip/m7/<name>.txt, <name>_back.txt):
# still = the converted grid, idle = 12 frames: a 1px breath (rows above 40% height drop 1px in
# frames 4-9) for walkers, a 1px hover of the whole grid for floaters and flyers. Feet on y = 91.
import sys,os
D=os.path.dirname(os.path.abspath(__file__))
INFO={
 'sprigby':('sprigby_v2','Sprigby (sprig + wallaby), Plant starter stage 1. Redrawn M7 from the owner\'s new ChatGPT pair (the old one is wip/sprigby_v1.px.js).',0),
 'cullet':('cullet','Cullet, Fire starter stage 2 (bible §13).',0),'vitric':('vitric','Vitric, Fire/Rock starter stage 3 (bible §13).',0),
 'tesnail':('tesnail','Tesnail, Spark/Metal starter stage 2 (bible §13).',0),'gauslug':('gauslug','Gauslug, Spark/Metal starter stage 3 (bible §13).',0),
 'fernaroo':('fernaroo','Fernaroo, Plant/Wind starter stage 2 (bible §13).',0),'scytharoo':('scytharoo','Scytharoo, Plant/Wind starter stage 3 (bible §13).',0),
 'gulpjaw':('gulpjaw','Gulpjaw, Water starter stage 2 (bible §13). Throat glow removed by the owner\'s call (kept for Harrowjaw).',0),'harrowjaw':('harrowjaw','Harrowjaw, Water/Dark starter stage 3 (bible §13).',0),
 'craterra':('craterra','Craterra, Rock/Dark Route 1 stage 2 (bible §15). Floats.',1),'singulith':('singulith','Singulith, Rock/Dark stage 3 (bible §15). Floats.',1),
 'contrailon':('contrailon','Contrailon, Wind/Metal stage 2 (bible §15). Flies.',1),'strafalcon':('strafalcon','Strafalcon, Wind/Metal stage 3 (bible §15). Flies.',1),
}
def load(f):
    L=open(os.path.join(D,f)).read().rstrip('\n').split('\n'); return eval(L[0]),L[1:]
for name in sys.argv[1:]:
    src,desc,fly=INFO[name]
    P,F=load(src+'.txt'); _,B=load(src+'_back.txt')
    out=[f'// {desc} 96x96 BW battle sprite.',
         f'// Converted from the owner\'s ChatGPT front+back pair (art/concepts/{src}_front.png, _back.png) with',
         '// art/tools/draft2sprite.py (wip/m7/conv.py), shared 15-colour palette. Generated by wip/m7/make_px.py.',
         f'// Idle: {"1px hover" if fly else "1px breath"}.','','pal({']+[f'  {k}: "{v}",' for k,v in sorted(P.items())]+['})','']
    def place(rows):
        h=len(rows); w=max(len(r) for r in rows); rows=[r.ljust(w,'.') for r in rows]
        x=(96-w)//2; y=(90-h) if fly else (92-h); return x,max(0,y),rows
    for tag,rows in (('FRONT',F),('BACK',B)):
        x,y,rows=place(rows)
        if fly or y+len(rows)>=96: frames=[rows]; dy=1
        else:
            s=int(len(rows)*0.4); frames=[rows,['.'*len(rows[0])]+rows[:s-1]+rows[s:]]; dy=0
        out.append(f'const {tag} = ['+','.join('`\n'+'\n'.join('  '+r for r in fr)+'`' for fr in frames)+']')
        out.append(f'const {tag}_XY = [{x}, {y}, {dy}]')
    for sfx,tag in (('', 'FRONT'),('_back','BACK')):
        out.append(f'sprite("{name}{sfx}", {{ w: 96, h: 96 }}, (c) => c.grid({tag}_XY[0], {tag}_XY[1], {tag}[0]))')
        out.append(f'anim("{name}{sfx}_idle", {{ w: 96, h: 96, frames: 12, fps: 10 }}, (c) => {{ const up = c.frame >= 4 && c.frame < 10; c.grid({tag}_XY[0], {tag}_XY[1] + (up ? {tag}_XY[2] : 0), {tag}[up ? {tag}.length - 1 : 0]) }})')
    open(os.path.join(D,'..','..',name+'.px.js'),'w').write('\n'.join(out)+'\n')
    print(name)
